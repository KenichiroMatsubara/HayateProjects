await Promise.all([
  writeFile(new URL('../src/generated.ts', import.meta.url), ts),
  writeFile(`${repositoryRoot}Hayate/crates/platform/mobile/android/src/generated/torimi_wire.rs`, rust),
  writeFile(`${repositoryRoot}Hayate/crates/platform/mobile/android/cpp/generated/torimi_wire.hpp`, cpp),
]);
